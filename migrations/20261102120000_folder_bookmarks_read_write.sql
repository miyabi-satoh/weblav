-- 前に作ったブックマークは読むだけの許可で、作り直すには利用者が窓でフォルダーを選び直すしかない
-- (許可は利用者が選んだときにしか増やせないため)。どちらの許可のブックマークかを覚え、
-- 読むだけのものは管理画面で選び直すよう知らせる (→ `api::roots::repick_root`)。
-- 前からある行は読むだけの許可 (0)。窓で選んで書くものは書き込みの許可 (1)。
ALTER TABLE folder_bookmarks ADD COLUMN read_write INTEGER NOT NULL DEFAULT 0;
