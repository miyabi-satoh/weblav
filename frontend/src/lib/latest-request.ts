/**
 * 「最後に開始した要求の結果だけを反映する」ための世代番号。
 *
 * ダイアログの中で階層を続けて辿ったり、開き直したりすると、前の要求の応答が後から
 * 届くことがある。そのまま状態へ書き込むと、古い階層や別のパスの結果が画面に残る。
 *
 * `$state` を使わないのは、この値自体を画面に出さないため (更新しても再描画は要らない)。
 */
export class LatestRequest {
	#seq = 0;

	/**
	 * 新しい要求を開始し、「この要求がまだ最新か」を返す判定関数を渡す。
	 * 応答を状態へ書き込む前に必ずこれを通す。
	 */
	begin(): () => boolean {
		const seq = ++this.#seq;
		return () => seq === this.#seq;
	}

	/**
	 * 進行中の要求をすべて過去のものにする。ダイアログを閉じるときに呼ぶ
	 * (次に開いたときの要求でも抑止できるが、それでは閉じている間に書き換わる)。
	 */
	invalidate(): void {
		this.#seq += 1;
	}
}
